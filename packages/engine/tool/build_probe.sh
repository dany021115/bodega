#!/bin/bash
# Regenerates lib/probe_data.dart from tool/probe.c.
# ZIG is the zig command, e.g. ZIG='python3 -m ziglang' after `pip install ziglang` in a venv.
set -euo pipefail
cd "$(dirname "$0")/.."
ZIG=${ZIG:-zig}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
$ZIG cc -target x86_64-windows-gnu -Os -s -o "$tmp/p64.exe" tool/probe.c -ldxguid
$ZIG cc -target x86-windows-gnu -Os -s -o "$tmp/p32.exe" tool/probe.c -ldxguid
{
  echo '// GENERATED by tool/build_probe.sh from tool/probe.c. Do not edit.'
  echo "const probe64Base64 = '$(base64 -i "$tmp/p64.exe" | tr -d '\n')';"
  echo "const probe32Base64 = '$(base64 -i "$tmp/p32.exe" | tr -d '\n')';"
} > lib/probe_data.dart
file "$tmp/p64.exe" "$tmp/p32.exe" | sed 's#.*/##'
