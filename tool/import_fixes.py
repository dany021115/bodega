#!/usr/bin/env python3
"""Regenerates packages/engine/lib/fixes_data.dart from highball-db (CC0-1.0).

    tool/import_fixes.py [--src DIR] [--commit SHA]

Without --src it downloads the pinned commit. Only what the engine can apply
is kept; everything else is counted and reported, never dropped silently:

  - environment steps whose variable is in ENV_ALLOWED,
  - registry steps under HKCU or HKLM\\Software,
  - dlloverride steps,
  - the notes and the known issues, as text (in English, as upstream wrote them).

Every kept step is tagged for the Mac, the only place upstream verified them:
a host applies only the steps tagged for it (see fixes.dart).
"""
import argparse
import glob
import io
import json
import os
import sys
import tarfile
import urllib.request

COMMIT = "7a008d598d5785089e3eb8b1866c8d430958a687"
REPO = "gauthierpiarrette/highball-db"
# Variables our Wine and Bodega know. HB_* belong to Highball's own engine patches,
# FEX_* and MVK_* to the arm64 line, and CX_* to CrossOver's build.
ENV_ALLOWED = {
    "ROSETTA_ADVERTISE_AVX",
    "D3DM_VENDOR_ID",
    "D3DM_DEVICE_ID",
    "D3DM_DEVICE_DESCRIPTION",
    "VKD3D_FEATURE_LEVEL",
    "VKD3D_SHADER_MODEL",
    "VKD3D_CONFIG",
    "DXVK_CONFIG",
}
REGISTRY_ROOTS = ("HKCU\\", "HKLM\\Software\\")
OUT = os.path.join(os.path.dirname(__file__), "..", "packages", "engine", "lib", "fixes_data.dart")


def fetch(commit):
    url = f"https://codeload.github.com/{REPO}/tar.gz/{commit}"
    with urllib.request.urlopen(url, timeout=120) as response:
        data = response.read()
    tar = tarfile.open(fileobj=io.BytesIO(data), mode="r:gz")
    root = tar.getnames()[0].split("/")[0]
    target = os.path.join(os.environ.get("TMPDIR", "/tmp"), f"highball-db-{commit[:7]}")
    tar.extractall(target, filter="data")
    return os.path.join(target, root)


def convert(recipe, appid, skipped):
    steps, notes = [], []
    for step in recipe["steps"]:
        kind = step["type"]
        if kind == "note":
            notes.append(step["text"])
        elif kind == "environment" and step["name"] in ENV_ALLOWED:
            steps.append({"type": "env", "name": step["name"], "value": step["value"], "platforms": ["mac"]})
        elif kind == "registry" and step["key"].startswith(REGISTRY_ROOTS):
            steps.append({
                "type": "registry", "key": step["key"], "name": step["name"],
                "valueType": step["valueType"], "data": step["data"], "platforms": ["mac"],
            })
        elif kind == "dlloverride":
            steps.append({"type": "dlloverride", "value": step["value"], "platforms": ["mac"]})
        else:
            label = step.get("name", "") if kind == "environment" else ""
            skipped.append(f"{recipe['id']}: {kind} {label}".rstrip())
    verified = recipe.get("lastVerified")
    return {
        "id": recipe["id"],
        "title": recipe["title"],
        "steam": appid,
        "optIn": bool(recipe.get("optIn")),
        "steps": steps,
        "notes": notes,
        "knownIssues": [
            {"symptom": i["symptom"], "cause": i.get("cause", ""), "fix": i.get("fix", "")}
            for i in recipe.get("knownIssues", [])
        ],
        "verified": {k: verified.get(k) for k in ("date", "engine", "chip")} if verified else None,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--src", help="a highball-db checkout; default: download the pinned commit")
    parser.add_argument("--commit", default=COMMIT)
    args = parser.parse_args()
    src = args.src or fetch(args.commit)

    games = {}
    for path in glob.glob(os.path.join(src, "db", "games", "*.json")):
        game = json.load(open(path))
        games[game["id"]] = game

    skipped, entries, without_appid = [], [], []
    for path in sorted(glob.glob(os.path.join(src, "recipes", "games", "*.json"))):
        recipe = json.load(open(path))
        appid = games.get(recipe["id"], {}).get("steam_appid")
        if not appid:
            without_appid.append(recipe["id"])
            continue
        entry = convert(recipe, appid, skipped)
        if not entry["steps"]:
            skipped.append(f"{recipe['id']}: no step the engine can apply, entry left out")
            continue
        entry["source"] = f"recipes/games/{recipe['id']}.json"
        entries.append(entry)

    text = json.dumps(entries, indent=1, ensure_ascii=False)
    if "'''" in text:
        sys.exit("a string holds ''', which the Dart raw string cannot carry")
    header = (
        f"/// Per-game fixes (F1), from {REPO} at {args.commit[:7]} (CC0-1.0), recipes/games/.\n"
        "/// Generated by tool/import_fixes.py: do not edit by hand. Text in the app, not a file,\n"
        "/// because `dart compile exe` carries no assets. Notes and known issues are in English, as upstream wrote them.\n"
        "/// Nothing here comes from CrossOver's data.\n"
        "const fixesCommit = '" + args.commit + "';\n"
        "const fixesJson = r'''\n"
    )
    with open(OUT, "w") as out:
        out.write(header + text + "\n''';\n")

    steps = sum(len(e["steps"]) for e in entries)
    print(f"{len(entries)} games, {steps} steps kept -> {os.path.normpath(OUT)}")
    print(f"left out, no steam_appid: {len(without_appid)}; steps not applicable: {len(skipped)}")
    for line in skipped:
        print("  skipped", line)


if __name__ == "__main__":
    main()
